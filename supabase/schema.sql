create or replace view public.shipment_live_view
with (security_invoker = true)
as
select
  s.*,
  os.code as origin_code,
  os.name as origin_name,
  os.city as origin_city,
  ds.code as destination_code,
  ds.name as destination_name,
  ds.city as destination_city,
  v.code as vehicle_code,
  v.registration_no,
  v.driver_name,
  v.status as vehicle_status,
  (
    select count(*)::int
    from public.alerts a
    where a.shipment_id = s.id
      and a.status = 'open'
  ) as open_alert_count
from public.shipments s
left join public.cold_storages os on os.id = s.origin_storage_id
left join public.cold_storages ds on ds.id = s.destination_storage_id
left join public.vehicles v on v.id = s.vehicle_id;

-- fleet_view uses v.*. If vehicle columns were added by an earlier partial run,
-- CREATE OR REPLACE VIEW can interpret the expanded column order as a rename.
-- Recreate the view cleanly so reruns are safe.
drop view if exists public.fleet_view cascade;

create view public.fleet_view
with (security_invoker = true)
as
select
  v.*,
  s.id as active_shipment_id,
  s.tracking_code as active_tracking_code,
  s.product_name as active_product_name,
  s.survival_score as shipment_survival_score,
  s.risk_level as shipment_risk_level
from public.vehicles v
left join lateral (
  select *
  from public.shipments s2
  where s2.vehicle_id = v.id
    and s2.status in ('scheduled','in_transit','delayed','quarantined')
  order by s2.updated_at desc
  limit 1
) s on true;


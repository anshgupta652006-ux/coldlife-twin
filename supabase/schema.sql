create table if not exists public.cold_storages (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  name text not null,
  city text not null,
  latitude double precision not null,
  longitude double precision not null,
  capacity_units integer not null default 0 check (capacity_units >= 0),
  current_load_units integer not null default 0 check (current_load_units >= 0),
  target_temp_min_c numeric(5,2) not null default 2,
  target_temp_max_c numeric(5,2) not null default 8,
  status text not null default 'operational'
    check (status in ('operational','warning','offline')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.vehicles (
  id uuid primary key default gen_random_uuid(),
  code text not null unique,
  registration_no text,
  driver_name text,
  vehicle_type text not null default 'reefer_truck',
  status text not null default 'idle'
    check (status in ('idle','in_transit','maintenance','alert','offline')),
  latitude double precision,
  longitude double precision,
  temperature_c numeric(6,2),
  humidity_pct numeric(6,2),
  battery_pct numeric(6,2) check (battery_pct is null or (battery_pct >= 0 and battery_pct <= 100)),
  speed_kmh numeric(7,2),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.shipments (
  id uuid primary key default gen_random_uuid(),
  tracking_code text not null unique,
  product_name text not null,
  batch_no text,
  quantity integer not null default 1 check (quantity > 0),

  origin_storage_id uuid references public.cold_storages(id) on delete set null,
  destination_storage_id uuid references public.cold_storages(id) on delete set null,
  vehicle_id uuid references public.vehicles(id) on delete set null,

  status text not null default 'scheduled'
    check (status in ('scheduled','in_transit','delayed','delivered','quarantined','cancelled')),
  priority text not null default 'normal'
    check (priority in ('normal','high','critical')),

  target_temp_min_c numeric(5,2) not null default 2,
  target_temp_max_c numeric(5,2) not null default 8,
  current_temp_c numeric(6,2),
  current_humidity_pct numeric(6,2),

  survival_score numeric(5,2) not null default 100
    check (survival_score >= 0 and survival_score <= 100),
  risk_level text not null default 'low'
    check (risk_level in ('low','medium','high','critical')),
  recommendation text not null default 'Continue monitoring.',

  latitude double precision,
  longitude double precision,

  started_at timestamptz,
  eta timestamptz,
  delivered_at timestamptz,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.telemetry (
  id bigint generated by default as identity primary key,
  shipment_id uuid not null references public.shipments(id) on delete cascade,
  vehicle_id uuid references public.vehicles(id) on delete set null,

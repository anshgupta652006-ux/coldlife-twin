create or replace function public.run_live_demo_tick()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  r record;
  v_tick bigint;
  v_phase integer;
  v_temp numeric;
  v_humidity numeric;
  v_survival numeric;
  v_risk text;
  v_risk_score numeric;
  v_speed numeric;
  v_battery numeric;
  v_fuel numeric;
  v_fuel_lph numeric;
  v_engine numeric;
  v_reefer numeric;
  v_lat double precision;
  v_lng double precision;
  v_driver_score numeric;
  v_eco numeric;
  v_overall numeric;
  v_reefer_health numeric;
  v_compressor numeric;
  v_door text;
begin
  for r in
    select
      s.*,
      v.code as vehicle_code,
      v.driver_name,
      v.battery_pct as vehicle_battery,
      v.speed_kmh as vehicle_speed,
      v.fuel_level_pct as vehicle_fuel,
      v.fuel_consumption_lph as vehicle_fuel_lph,
      v.odometer_km,
      v.id as joined_vehicle_id
    from public.shipments s
    join public.vehicles v on v.id = s.vehicle_id
    where s.tracking_code in ('CLT-2401','CLT-2402','CLT-2403','CLT-2404')
  loop
    insert into public.demo_live_state(shipment_id, tick_no, updated_at)
    values (r.id, 1, now())
    on conflict (shipment_id)
    do update set
      tick_no = public.demo_live_state.tick_no + 1,
      updated_at = now()
    returning tick_no into v_tick;

    v_phase := mod(v_tick, 36);

    -- Different live patterns give the four hackathon demo shipments
    -- visibly different graphs.
    if r.tracking_code = 'CLT-2401' then
      v_temp := 4.15 + 0.32 * sin(v_tick::double precision / 2.2);
      v_humidity := 57 + 2.5 * sin(v_tick::double precision / 3.1);
      v_survival := 98.2 - 0.7 * abs(sin(v_tick::double precision / 5.0));
      v_speed := 46 + 8 * sin(v_tick::double precision / 2.8);
      v_driver_score := 94;
      v_eco := 92;
      v_overall := 96;
      v_reefer_health := 97;
      v_compressor := 95;
    elsif r.tracking_code = 'CLT-2402' then
      if v_phase < 14 then
        v_temp := 4.7 + (v_phase * 0.36);
        v_survival := 94 - (v_phase * 1.35);
      elsif v_phase < 24 then
        v_temp := 9.7 - ((v_phase - 14) * 0.46);
        v_survival := 75.5 + ((v_phase - 14) * 1.35);
      else
        v_temp := 5.0 + 0.25 * sin(v_tick::double precision / 2.0);
        v_survival := 89 + 1.0 * sin(v_tick::double precision / 5.0);
      end if;
      v_humidity := 62 + 5 * sin(v_tick::double precision / 3.5);
      v_speed := 40 + 12 * sin(v_tick::double precision / 2.4);
      v_driver_score := 87;
      v_eco := 83;
      v_overall := 88;
      v_reefer_health := case when v_phase < 14 then 78 else 88 end;
      v_compressor := case when v_phase < 14 then 71 else 86 end;
    elsif r.tracking_code = 'CLT-2403' then
      v_temp := 10.4 + 1.25 * sin(v_tick::double precision / 2.6);
      v_humidity := 73 + 4 * sin(v_tick::double precision / 4.0);
      v_survival := greatest(38, 58 - (mod(v_tick, 25) * 0.65));
      v_speed := 28 + 8 * sin(v_tick::double precision / 2.9);
      v_driver_score := 76;
      v_eco := 71;
      v_overall := 68;
      v_reefer_health := 58;
      v_compressor := 54;
    else
      v_temp := 3.85 + 0.28 * sin(v_tick::double precision / 2.1);
      v_humidity := 54 + 2.2 * sin(v_tick::double precision / 4.2);
      v_survival := 96.5 - 0.9 * abs(sin(v_tick::double precision / 4.0));
      v_speed := 54 + 9 * sin(v_tick::double precision / 2.7);
      v_driver_score := 91;
      v_eco := 88;
      v_overall := 94;
      v_reefer_health := 95;
      v_compressor := 93;
    end if;

    v_risk :=
      case
        when v_survival < 60 or v_temp >= 10 then 'critical'
        when v_survival < 78 or v_temp > r.target_temp_max_c then 'high'
        when v_survival < 90 then 'medium'
        else 'low'
      end;

    v_risk_score :=
      case v_risk
        when 'critical' then greatest(82, 100 - v_survival)
        when 'high' then greatest(62, 100 - v_survival)
        when 'medium' then greatest(35, 100 - v_survival)
        else greatest(5, 100 - v_survival)
      end;

    v_battery := greatest(
      48,
      coalesce(r.vehicle_battery, 94) - 0.015 + (random() - 0.5) * 0.08
    );

    v_engine := 82 + (v_speed / 22.0) + (random() - 0.5) * 2.0;
    v_reefer := least(100, greatest(45, 60 + abs(v_temp - 4.5) * 6 + random() * 5));
    v_fuel_lph := greatest(4.5, 6.0 + (v_speed / 18.0) + (v_reefer / 45.0));
    v_fuel := coalesce(r.vehicle_fuel, 82) - greatest(0.008, v_fuel_lph / 3600.0 * 10.0 / 1.2);

    -- Auto-refuel in the simulated demo when fuel gets low so the online
    -- demo can keep running indefinitely.
    if v_fuel < 18 then
      v_fuel := 88 + random() * 5;
    end if;

    v_lat := coalesce(r.latitude, 28.60) + 0.00045 * sin(v_tick::double precision / 3.0);
    v_lng := coalesce(r.longitude, 77.20) + 0.00055 * cos(v_tick::double precision / 3.0);

    update public.shipments
    set
      current_temp_c = round(v_temp, 2),
      current_humidity_pct = round(v_humidity, 2),
      survival_score = round(v_survival, 2),
      risk_level = v_risk,
      latitude = v_lat,
      longitude = v_lng,
      status = case when v_risk = 'critical' then 'quarantined' else 'in_transit' end,
      recommendation =
        case
          when v_risk = 'critical'
            then 'Critical excursion: maintain quarantine and escalate for quality review.'
          when v_risk = 'high'
            then 'Cooling performance degraded: restore refrigeration and increase monitoring.'
          when v_risk = 'medium'
            then 'Watch closely: conditions are trending toward the configured limit.'
          else 'Conditions stable. Continue standard monitoring.'
        end
    where id = r.id;

    update public.vehicles
    set
      latitude = v_lat,
      longitude = v_lng,
      temperature_c = round(v_temp, 2),
      humidity_pct = round(v_humidity, 2),
      battery_pct = round(v_battery, 2),
      speed_kmh = round(v_speed, 2),
      fuel_level_pct = round(v_fuel, 2),
      fuel_consumption_lph = round(v_fuel_lph, 2),
      engine_temp_c = round(v_engine, 2),
      reefer_power_pct = round(v_reefer, 2),
      odometer_km = coalesce(odometer_km, 45000) + (v_speed * 10.0 / 3600.0),
      status = case when v_risk in ('critical','high') then 'alert' else 'in_transit' end
    where id = r.vehicle_id;

    insert into public.telemetry (
      shipment_id, vehicle_id, recorded_at,
      temperature_c, humidity_pct, latitude, longitude,
      battery_pct, speed_kmh, door_open,
      fuel_level_pct, fuel_consumption_lph, engine_temp_c,
      reefer_power_pct, survival_score
    ) values (
      r.id, r.vehicle_id, now(),
      round(v_temp,2), round(v_humidity,2), v_lat, v_lng,
      round(v_battery,2), round(v_speed,2), false,
      round(v_fuel,2), round(v_fuel_lph,2), round(v_engine,2),
      round(v_reefer,2), round(v_survival,2)
    );

    insert into public.risk_history (
      shipment_id, recorded_at, survival_score, risk_score, risk_level
    ) values (
      r.id, now(), round(v_survival,2), round(v_risk_score,2), v_risk
    );

    insert into public.driver_behavior_snapshots (
      shipment_id, vehicle_id, driver_name, style,
      driver_score, avg_speed_kmh, max_speed_kmh,
      harsh_braking_count, harsh_accel_count, cornering_count, speeding_events,
      idle_minutes, fatigue_score, eco_score, recorded_at
    ) values (
      r.id, r.vehicle_id, coalesce(r.driver_name, 'ColdLife Driver'),
      case
        when v_driver_score >= 92 then 'smooth'
        when v_driver_score >= 85 then 'balanced'
        else 'aggressive'
      end,
      v_driver_score + (random() - 0.5) * 2,
      greatest(20, v_speed - 4),
      v_speed + 8 + random() * 5,
      case when random() > 0.86 then 1 else 0 end,
      case when random() > 0.88 then 1 else 0 end,
      case when random() > 0.90 then 1 else 0 end,
      case when v_speed > 58 and random() > 0.70 then 1 else 0 end,
      round((random() * 2.2)::numeric, 2),
      greatest(20, 100 - v_driver_score + random() * 8),
      v_eco + (random() - 0.5) * 3,
      now()
    );

    v_door := case when mod(v_tick, 47) = 0 then 'open' else 'closed' end;

    insert into public.vehicle_health_snapshots (
      vehicle_id,
      overall_health_pct, reefer_health_pct, compressor_efficiency_pct, battery_health_pct,
      battery_pct, fuel_pct, fuel_consumption_lph, engine_temp_c, coolant_pct,
      tyre_pressure_psi, gps_signal_pct, door_status, service_due_km,
      reefer_runtime_hours, recorded_at
    ) values (
      r.vehicle_id,
      v_overall + (random() - 0.5) * 2,
      v_reefer_health + (random() - 0.5) * 2,
      v_compressor + (random() - 0.5) * 2,
      v_battery,
      v_battery,
      v_fuel,
      v_fuel_lph,
      v_engine,
      91 + (random() - 0.5) * 3,
      34.5 + (random() - 0.5) * 1.2,
      97 + (random() - 0.5) * 2,
      v_door,
      greatest(400, 3200 - (mod(v_tick, 120) * 8)),
      coalesce(r.odometer_km, 45000) / 40.0,
      now()
    );

    -- Periodic custody milestones make the custody timeline keep changing too.
    if mod(v_tick, 18) = 0 then
      insert into public.custody_events (
        shipment_id, event_type, title, description,
        actor, location, status, recorded_at
      ) values (
        r.id,
        'checkpoint',
        'Live route checkpoint verified',
        'Telemetry verified: ' ||
        round(v_temp, 1)::text || '°C, survival ' ||
        round(v_survival, 0)::text || '%, fuel ' ||
        round(v_fuel, 0)::text || '%.',
        coalesce(r.driver_name, 'ColdLife Driver'),
        'Live GPS checkpoint',
        'active',
        now()
      );
    end if;

    -- Bound history size so a long-running demo does not grow forever.
    delete from public.telemetry
      where id in (
        select id from public.telemetry
        where shipment_id = r.id
        order by recorded_at desc
        offset 360
      );

    delete from public.risk_history
      where id in (
        select id from public.risk_history
        where shipment_id = r.id
        order by recorded_at desc
        offset 360
      );

    delete from public.driver_behavior_snapshots
      where id in (
        select id from public.driver_behavior_snapshots
        where shipment_id = r.id
        order by recorded_at desc
        offset 120
      );

    delete from public.vehicle_health_snapshots
      where id in (
        select id from public.vehicle_health_snapshots
        where vehicle_id = r.vehicle_id
        order by recorded_at desc
        offset 120
      );

    delete from public.custody_events
      where id in (
        select id from public.custody_events
        where shipment_id = r.id
        order by recorded_at desc
        offset 60
      );
  end loop;

  return jsonb_build_object(
    'ok', true,
    'updated_at', now(),
    'message', 'ColdLife live demo tick completed'
  );
end;
$$;


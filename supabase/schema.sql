create or replace function public.get_dashboard_data()
returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
  select jsonb_build_object(
    'summary',
      jsonb_build_object(
        'totalShipments', (select count(*) from public.shipments),
        'activeShipments', (
          select count(*) from public.shipments
          where status in ('scheduled','in_transit','delayed','quarantined')
        ),
        'criticalShipments', (
          select count(*) from public.shipments
          where risk_level = 'critical' or status = 'quarantined'
        ),
        'openAlerts', (
          select count(*) from public.alerts where status = 'open'
        ),
        'fleetActive', (
          select count(*) from public.vehicles where status = 'in_transit'
        ),
        'averageSurvivalScore', (
          select coalesce(round(avg(survival_score), 1), 0)
          from public.shipments
        )
      ),
    'shipments',
      coalesce((
        select jsonb_agg(to_jsonb(x))
        from (
          select *
          from public.shipment_live_view
          order by
            case risk_level
              when 'critical' then 1
              when 'high' then 2
              when 'medium' then 3
              else 4
            end,
            updated_at desc
          limit 8
        ) x
      ), '[]'::jsonb),
    'alerts',
      coalesce((
        select jsonb_agg(to_jsonb(a))
        from (
          select *
          from public.alerts
          order by created_at desc
          limit 8
        ) a
      ), '[]'::jsonb),
    'fleet',
      coalesce((
        select jsonb_agg(to_jsonb(f))
        from (
          select *
          from public.fleet_view
          order by code
        ) f
      ), '[]'::jsonb),
    'coldStorages',
      coalesce((
        select jsonb_agg(to_jsonb(c))
        from (
          select *
          from public.cold_storages
          order by name
        ) c
      ), '[]'::jsonb)
  );
$$;

-- ---------- RPC: CONTROLLED SHIPMENT ACTIONS ----------
-- Allows a public hackathon demo to perform a limited set of actions
-- without granting direct UPDATE permission on shipments.

create or replace function public.perform_shipment_action(
  p_shipment_id uuid,
  p_action text,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_action text := upper(trim(p_action));
  v_row public.shipments%rowtype;
begin
  if v_action not in ('QUARANTINE','PRIORITIZE','RESUME','MARK_DELIVERED','RESET_MONITORING') then
    raise exception 'Unsupported shipment action: %', p_action;
  end if;

  if v_action = 'QUARANTINE' then
    update public.shipments
    set status = 'quarantined',
        risk_level = 'critical',
        recommendation = 'Hold shipment for trained quality review before release.'
    where id = p_shipment_id;

  elsif v_action = 'PRIORITIZE' then
    update public.shipments
    set priority = 'critical',
        recommendation = 'Prioritize route and receiving handoff; continue continuous monitoring.'
    where id = p_shipment_id;

  elsif v_action = 'RESUME' then
    update public.shipments
    set status = 'in_transit',
        recommendation = 'Transport resumed. Continue enhanced temperature monitoring.'
    where id = p_shipment_id;

  elsif v_action = 'MARK_DELIVERED' then
    update public.shipments
    set status = 'delivered',
        delivered_at = now(),
        recommendation = 'Shipment delivered. Complete receiving quality checks.'
    where id = p_shipment_id;

  elsif v_action = 'RESET_MONITORING' then
    update public.shipments
    set risk_level = 'low',
        recommendation = 'Continue monitoring.'
    where id = p_shipment_id;

    update public.alerts
    set status = 'resolved',
        resolved_at = now()
    where shipment_id = p_shipment_id
      and status <> 'resolved';
  end if;

  if not found then
    raise exception 'Shipment not found';
  end if;

  insert into public.shipment_actions(shipment_id, action, notes)
  values (p_shipment_id, v_action, p_notes);

  select * into v_row from public.shipments where id = p_shipment_id;

  return jsonb_build_object(
    'ok', true,
    'action', v_action,
    'shipment', to_jsonb(v_row)
  );
end;
$$;

create or replace function public.acknowledge_alert(p_alert_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_alert public.alerts%rowtype;
begin
  update public.alerts
  set status = 'acknowledged',
      acknowledged_at = now()
  where id = p_alert_id
    and status = 'open'
  returning * into v_alert;

  if v_alert.id is null then
    select * into v_alert from public.alerts where id = p_alert_id;
  end if;

  if v_alert.id is null then
    raise exception 'Alert not found';
  end if;

  return jsonb_build_object('ok', true, 'alert', to_jsonb(v_alert));
end;
$$;

-- ---------- RPC: SIMULATION TICK ----------

create or replace function public.run_simulation_tick(p_scenario_key text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_scenario public.scenarios%rowtype;
  v_shipment public.shipments%rowtype;
  v_tick integer;
  v_temp numeric(6,2);
  v_humidity numeric(6,2);
  v_score numeric(5,2);
  v_risk text;
  v_recommendation text;
  v_status text;
  v_payload jsonb;
begin
  select * into v_scenario
  from public.scenarios
  where scenario_key = p_scenario_key
    and is_active = true;

  if v_scenario.id is null then
    raise exception 'Scenario not found: %', p_scenario_key;
  end if;

  select * into v_shipment
  from public.shipments
  where id = v_scenario.shipment_id
  for update;

  if v_shipment.id is null then
    raise exception 'Scenario has no shipment';
  end if;

  select coalesce(max(tick_no), 0) + 1 into v_tick
  from public.simulation_ticks
  where scenario_id = v_scenario.id;

  v_temp := coalesce(v_shipment.current_temp_c, 4.5);
  v_humidity := coalesce(v_shipment.current_humidity_pct, 58);
  v_score := v_shipment.survival_score;
  v_risk := v_shipment.risk_level;
  v_recommendation := v_shipment.recommendation;
  v_status := v_shipment.status;

  if p_scenario_key = 'healthy_delivery' then
    v_temp := greatest(2.5, least(6.0, v_temp + ((random() - 0.5) * 0.5)));
    v_humidity := greatest(45, least(70, v_humidity + ((random() - 0.5) * 2)));
    v_score := least(100, v_score + 0.20);
    v_risk := 'low';
    v_status := 'in_transit';
    v_recommendation := 'Conditions stable. Continue standard monitoring.';

  elsif p_scenario_key = 'recoverable_cooling_failure' then
    if v_tick <= 5 then
      v_temp := least(10.5, v_temp + 0.85);
      v_score := greatest(60, v_score - 2.4);
    else
      v_temp := greatest(5.0, v_temp - 0.95);
      v_score := least(92, v_score + 0.7);
    end if;

    v_humidity := greatest(45, least(78, v_humidity + ((random() - 0.35) * 3)));

    if v_temp > v_shipment.target_temp_max_c then
      v_risk := case when v_temp >= 9.5 then 'high' else 'medium' end;
      v_recommendation := 'Cooling excursion detected. Restore refrigeration and increase monitoring frequency.';

      if not exists (
        select 1 from public.alerts
        where shipment_id = v_shipment.id
          and alert_type = 'cooling_failure'
          and status = 'open'
      ) then
        insert into public.alerts(
          shipment_id, vehicle_id, severity, alert_type, title, message, recommended_action
        ) values (
          v_shipment.id,
          v_shipment.vehicle_id,
          'warning',
          'cooling_failure',
          'Cooling performance degraded',
          'Shipment temperature is above the configured target range.',
          'Restore cooling and review recent telemetry.'
        );
      end if;
    else
      v_risk := 'low';
      v_recommendation := 'Cooling recovered. Continue enhanced monitoring.';
      update public.alerts
      set status = 'resolved', resolved_at = now()
      where shipment_id = v_shipment.id
        and alert_type = 'cooling_failure'
        and status <> 'resolved';
    end if;

  elsif p_scenario_key = 'critical_quarantine' then
    v_temp := least(15.0, v_temp + 1.35);
    v_humidity := least(85, v_humidity + 1.5);
    v_score := greatest(20, v_score - 5.5);
    v_risk := 'critical';
    v_status := 'quarantined';
    v_recommendation := 'Quarantine shipment and require trained quality review before release.';

    if not exists (
      select 1 from public.alerts
      where shipment_id = v_shipment.id
        and alert_type = 'critical_temperature_excursion'
        and status = 'open'
    ) then
      insert into public.alerts(
        shipment_id, vehicle_id, severity, alert_type, title, message, recommended_action
      ) values (
        v_shipment.id,
        v_shipment.vehicle_id,
        'critical',
        'critical_temperature_excursion',
        'Critical cold-chain excursion',
        'Temperature excursion has exceeded the demo critical threshold.',
        'Quarantine and escalate for trained quality review.'
      );
    end if;

  elsif p_scenario_key = 'priority_shipment' then
    v_temp := greatest(3.0, least(6.5, v_temp + ((random() - 0.5) * 0.45)));
    v_humidity := greatest(45, least(70, v_humidity + ((random() - 0.5) * 2)));
    v_score := greatest(88, least(99, v_score + 0.1));
    v_risk := 'low';
    v_status := 'in_transit';
    v_recommendation := 'Priority shipment: maintain expedited route and receiving handoff.';

    update public.shipments
    set priority = 'critical'
    where id = v_shipment.id;
  else
    raise exception 'Scenario handler missing for: %', p_scenario_key;
  end if;

  update public.shipments
  set current_temp_c = round(v_temp, 2),
      current_humidity_pct = round(v_humidity, 2),
      survival_score = round(v_score, 2),
      risk_level = v_risk,
      status = v_status,
      recommendation = v_recommendation,
      latitude = coalesce(latitude, 28.6139) + ((random() - 0.5) * 0.012),
      longitude = coalesce(longitude, 77.2090) + ((random() - 0.5) * 0.012)
  where id = v_shipment.id
  returning * into v_shipment;

  if v_shipment.vehicle_id is not null then
    update public.vehicles
    set temperature_c = v_shipment.current_temp_c,
        humidity_pct = v_shipment.current_humidity_pct,
        latitude = v_shipment.latitude,
        longitude = v_shipment.longitude,
        status = case
          when v_status = 'quarantined' then 'alert'
          when v_status = 'in_transit' then 'in_transit'
          else status
        end
    where id = v_shipment.vehicle_id;
  end if;

  insert into public.telemetry(
    shipment_id, vehicle_id, temperature_c, humidity_pct,
    latitude, longitude, battery_pct, speed_kmh, door_open
  )
  select
    v_shipment.id,
    v_shipment.vehicle_id,
    v_shipment.current_temp_c,
    v_shipment.current_humidity_pct,
    v_shipment.latitude,
    v_shipment.longitude,
    coalesce(v.battery_pct, 90),
    coalesce(v.speed_kmh, 42),
    false
  from public.vehicles v
  where v.id = v_shipment.vehicle_id;

  if v_shipment.vehicle_id is null then
    insert into public.telemetry(
      shipment_id, temperature_c, humidity_pct, latitude, longitude
    ) values (
      v_shipment.id,
      v_shipment.current_temp_c,
      v_shipment.current_humidity_pct,
      v_shipment.latitude,
      v_shipment.longitude
    );
  end if;

  v_payload := jsonb_build_object(
    'scenario', p_scenario_key,
    'tick', v_tick,
    'temperature_c', v_shipment.current_temp_c,
    'humidity_pct', v_shipment.current_humidity_pct,
    'survival_score', v_shipment.survival_score,
    'risk_level', v_shipment.risk_level,
    'status', v_shipment.status,
    'recommendation', v_shipment.recommendation
  );

  insert into public.simulation_ticks(scenario_id, shipment_id, tick_no, payload)
  values (v_scenario.id, v_shipment.id, v_tick, v_payload);

  return jsonb_build_object(
    'ok', true,
    'scenario', p_scenario_key,
    'tick', v_tick,
    'shipment', to_jsonb(v_shipment),
    'payload', v_payload
  );
end;
$$;

